import express from "express";
import rateLimit from "express-rate-limit";
import adminAuth from "../middleware/adminAuth.js";
import requireRole from "../middleware/requireRole.js";
import { asyncRoute } from "../utils/http.js";
import * as handlers from "../controllers/engagementController.js";

export const publicFormsLimiter = rateLimit({ windowMs: 15 * 60000, max: 20, standardHeaders: true, legacyHeaders: false, message: { success: false, message: "Too many submissions. Please try again later." } });
export const publicCommentRouter = express.Router({ mergeParams: true });
publicCommentRouter.get("/", asyncRoute(handlers.listPublicComments));
publicCommentRouter.post("/", publicFormsLimiter, asyncRoute(handlers.submitComment));
export const publicEngagementRouter = express.Router();
publicEngagementRouter.post("/contact", publicFormsLimiter, asyncRoute(handlers.submitContact));
publicEngagementRouter.post("/newsletter/subscribe", publicFormsLimiter, asyncRoute(handlers.subscribe));
publicEngagementRouter.post("/newsletter/confirm", publicFormsLimiter, asyncRoute(handlers.confirmSubscriber));
publicEngagementRouter.post("/newsletter/unsubscribe", publicFormsLimiter, asyncRoute(handlers.unsubscribe));
publicEngagementRouter.get("/site/settings", asyncRoute(handlers.readSettings));
export const adminEngagementRouter = express.Router();
adminEngagementRouter.use(["/comments", "/contact-submissions", "/newsletter-subscribers", "/settings/general"], adminAuth);
const moderators = requireRole("editor", "super_admin");
const owner = requireRole("super_admin");
adminEngagementRouter.get("/comments", moderators, asyncRoute(handlers.listAdminComments));
adminEngagementRouter.patch("/comments/:id/status", moderators, asyncRoute(handlers.moderateComment));
adminEngagementRouter.get("/contact-submissions", moderators, asyncRoute(handlers.listContacts));
adminEngagementRouter.get("/contact-submissions/:id", moderators, asyncRoute(handlers.getContact));
adminEngagementRouter.patch("/contact-submissions/:id/status", moderators, asyncRoute(handlers.updateContact));
adminEngagementRouter.get("/newsletter-subscribers", owner, asyncRoute(handlers.listSubscribers));
adminEngagementRouter.get("/settings/general", owner, asyncRoute(handlers.readSettings));
adminEngagementRouter.patch("/settings/general", owner, asyncRoute(handlers.saveSettings));
